#!/usr/bin/env python3
"""Bake the dumpie package into a single self-contained file and refresh installers.

Development happens in ``src/dumpie/`` as clean modules. What a user installs and
runs is one file. This script amalgamates the package into that file and embeds it
into ``install.sh`` and ``install.ps1`` so source, the shipped script, and both
installers never drift. Run it after changing anything under ``src/dumpie/``:

    python build.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PKG = ROOT / "src" / "dumpie"

# Concatenation order respects load order: a module may use names defined above it.
MODULE_ORDER = ["fsutil", "ui", "extract", "flatten", "menu", "cli"]

_INTRA_IMPORT = re.compile(r"^from\s+(\.|dumpie[\s.])")
_FUTURE_IMPORT = re.compile(r"^from\s+__future__\s+import")
_IMPORT = re.compile(r"^(import\s+\w|from\s+[\w.]+\s+import)")


def _read_version() -> str:
    text = (PKG / "__init__.py").read_text(encoding="utf-8")
    match = re.search(r'__version__\s*=\s*"([^"]+)"', text)
    if not match:
        raise SystemExit("could not find __version__ in src/dumpie/__init__.py")
    return match.group(1)


def _strip_module_docstring(lines: list[str]) -> list[str]:
    """Drop a leading module docstring so only one survives in the amalgamation."""
    i = 0
    while i < len(lines) and lines[i].strip() == "":
        i += 1
    if i >= len(lines):
        return lines
    stripped = lines[i].lstrip()
    if not (stripped.startswith('"""') or stripped.startswith("'''")):
        return lines
    quote = stripped[:3]
    if stripped.count(quote) >= 2 and len(stripped) > 3:  # single-line docstring
        return lines[i + 1 :]
    i += 1
    while i < len(lines) and quote not in lines[i]:
        i += 1
    return lines[i + 1 :]


def amalgamate() -> str:
    """Return the full single-file dumpie source built from the package."""
    version = _read_version()
    external_imports: list[str] = []
    seen: set[str] = set()
    bodies: list[str] = []

    for name in MODULE_ORDER:
        lines = _strip_module_docstring((PKG / f"{name}.py").read_text(encoding="utf-8").splitlines())
        body: list[str] = []
        for line in lines:
            if _INTRA_IMPORT.match(line) or _FUTURE_IMPORT.match(line):
                continue
            if _IMPORT.match(line):
                key = line.strip()
                if key not in seen:
                    seen.add(key)
                    external_imports.append(line.rstrip())
                continue
            body.append(line.rstrip("\n"))
        banner = f"# ── {name} " + "─" * (58 - len(name))
        bodies.append(banner + "\n" + "\n".join(body).strip("\n"))

    header = "\n".join(
        [
            "#!/usr/bin/env python3",
            '"""dumpie — unpack every zip under a folder, then quarantine the originals.',
            "",
            "GENERATED from src/dumpie/ by build.py — do not edit this file by hand.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            *sorted(external_imports),
            "",
            f'__version__ = "{version}"',
        ]
    )
    footer = "\n".join(
        [
            'if __name__ == "__main__":',
            "    import sys",
            "    try:",
            "        sys.exit(main())",
            "    except KeyboardInterrupt:",
            '        console.print("\\n[muted]aborted[/muted]")',
            "        sys.exit(130)",
        ]
    )
    return header + "\n\n\n" + "\n\n\n".join(bodies) + "\n\n\n" + footer + "\n"


def _embed(text: str, opening: str, closing: str, code: str) -> str:
    pattern = re.compile(re.escape(opening) + r".*?" + re.escape(closing), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"could not find embed markers {opening!r}..{closing!r}")
    return pattern.sub(lambda _m: opening + code + closing, text, count=1)


def main() -> int:
    code = amalgamate()
    compile(code, "dumpie", "exec")  # fail loudly if amalgamation produced bad source

    (ROOT / "dumpie").write_text(code, encoding="utf-8", newline="\n")

    sh = ROOT / "install.sh"
    sh.write_text(
        _embed(sh.read_text(encoding="utf-8"), "<< 'DUMPIE_EOF'\n", "DUMPIE_EOF\n", code),
        encoding="utf-8",
        newline="\n",
    )

    ps1 = ROOT / "install.ps1"
    ps1.write_text(
        _embed(ps1.read_text(encoding="utf-8"), "$source = @'\n", "'@\n", code),
        encoding="utf-8",
    )

    print(f"baked dumpie v{_read_version()} -> dumpie, install.sh, install.ps1")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

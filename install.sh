# ── extract ───────────────────────────────────────────────────
class Mode(enum.Enum):
    """How a run lays out the files it unpacks."""

    MODULAR = "modular"  # a folder per zip, internal structure kept
    FLAT = "flat"        # every file into the target, internal folders stripped


def collect_zips(target: Path) -> list[Path]:
    """All zips under ``target``, recursive. Skips any prior ``_dumped*`` archives."""
    found = []
    for p in sorted(target.rglob("*")):
        if not (p.is_file() and p.suffix.lower() == ".zip"):
            continue
        rel_parts = p.relative_to(target).parts
        if any(part.startswith(ARCHIVE_DIRNAME) for part in rel_parts[:-1]):
            continue
        found.append(p)
    return found


def _flat_members(zf: zipfile.ZipFile) -> list[tuple[zipfile.ZipInfo, str]]:
    """File members of a zip paired with their basename (internal folders stripped)."""
    out = []
    for member in zf.infolist():
        if member.is_dir():
            continue
        base = member.filename.replace("\\", "/").rstrip("/").rsplit("/", 1)[-1]
        if base:
            out.append((member, base))
    return out


def _sweep(zp: Path, archive_dir: Path, rel: Path) -> None:
    """Move a processed zip into the archive dir, mirroring its relative path."""
    slot = archive_dir / rel
    slot.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(zp), str(slot))


def _extract_modular(zp: Path, target: Path, archive_dir: Path, rel: Path) -> Path:
    """Unpack one zip into a folder of its own name. Returns the dest, relative to target."""
    dest = unique_dir(zp.parent / zp.stem)
    try:
        with zipfile.ZipFile(zp) as zf:
            bad = zf.testzip()
            if bad is not None:
                raise zipfile.BadZipFile(f"corrupt member: {bad}")
            dest.mkdir(parents=True)
            zf.extractall(dest)
    except (zipfile.BadZipFile, OSError):
        if dest.exists() and not any(dest.iterdir()):
            dest.rmdir()
        raise
    _sweep(zp, archive_dir, rel)
    return dest.relative_to(target)


def _extract_flat(zp: Path, target: Path, archive_dir: Path) -> int:
    """Unpack one zip's files straight into ``target``, folders stripped.

    Returns the number of files that had to be auto-numbered to avoid a collision.
    Re-seeds its name allocator from the live directory each call, so files written
    by earlier zips in the same run are accounted for.
    """
    alloc = NameAllocator(listdir_names(target))
    written: list[Path] = []
    renamed = 0
    try:
        with zipfile.ZipFile(zp) as zf:
            bad = zf.testzip()
            if bad is not None:
                raise zipfile.BadZipFile(f"corrupt member: {bad}")
            for member, base in _flat_members(zf):
                chosen, was_renamed = alloc.take(base)
                renamed += was_renamed
                dest = target / chosen
                with zf.open(member) as src, open(dest, "wb") as out:
                    shutil.copyfileobj(src, out)
                written.append(dest)
    except (zipfile.BadZipFile, OSError):
        for f in written:  # a corrupt zip leaves nothing behind
            try:
                f.unlink()
            except OSError:
                pass
        raise
    return renamed


def _preview(target: Path, zips: list[Path], mode: Mode) -> int:
    """Report what a run would do without writing anything. Returns exit code 0."""
    alloc = NameAllocator(listdir_names(target)) if mode is Mode.FLAT else None
    for zp in zips:
        rel = zp.relative_to(target)
        if mode is Mode.MODULAR:
            dest_rel = rel.parent / zp.stem
            console.print(f"  [accent]·[/accent] {rel} [muted]→ {dest_rel}/[/muted]")
            continue
        try:
            with zipfile.ZipFile(zp) as zf:
                files = _flat_members(zf)
        except (zipfile.BadZipFile, OSError) as e:
            console.print(f"  [bad]✗[/bad] {rel} [muted]{e}[/muted]")
            continue
        assert alloc is not None
        renamed = sum(alloc.take(base)[1] for _, base in files)
        extra = f", {renamed} renamed" if renamed else ""
        console.print(f"  [accent]·[/accent] {rel} [muted]→ {len(files)} file(s){extra}[/muted]")
    console.print("\n  [muted]dry run — nothing written.[/muted]\n")
    return 0


def run(target: Path, mode: Mode, *, dry_run: bool = False) -> int:
    """Unpack every zip under ``target``. Returns a process exit code (0 ok, 1 errors)."""
    zips = collect_zips(target)
    if not zips:
        console.print(f"\n  [warn]nothing to do[/warn] — no zip files under [muted]{target}[/muted]\n")
        return 0

    console.print(f"\n  found [b]{len(zips)}[/b] zip{'s' if len(zips) != 1 else ''}\n")

    if dry_run:
        return _preview(target, zips, mode)

    archive_dir = unique_dir(target / ARCHIVE_DIRNAME)
    archive_dir.mkdir(parents=True)

    ok = failed = renamed = 0
    with console.status("[b]unpacking…[/b]", spinner="dots"):
        for zp in zips:
            rel = zp.relative_to(target)
            try:
                if mode is Mode.FLAT:
                    n = _extract_flat(zp, target, archive_dir)
                    _sweep(zp, archive_dir, rel)
                    renamed += n
                    note = f" ({n} renamed)" if n else ""
                    console.print(f"  [ok]✓[/ok] {rel} [muted]→ flattened{note}[/muted]")
                else:
                    dest = _extract_modular(zp, target, archive_dir, rel)
                    console.print(f"  [ok]✓[/ok] {rel} [muted]→ {dest}/[/muted]")
                ok += 1
            except (zipfile.BadZipFile, OSError) as e:
                failed += 1
                console.print(f"  [bad]✗[/bad] {rel} [muted]{e}[/muted]")

    if ok == 0 and archive_dir.exists() and not any(archive_dir.iterdir()):
        archive_dir.rmdir()

    rows = [("unpacked", f"[ok]{ok}[/ok]" + (f"  [bad]{failed} failed[/bad]" if failed else ""))]
    if mode is Mode.FLAT and renamed:
        rows.append(("auto-numbered", f"{renamed} file{'s' if renamed != 1 else ''}"))
    rows.append(("source", str(target)))
    if ok:
        rows.append(("archived zips", str(archive_dir)))
    summary("complete" if not failed else "complete with errors", not failed, rows)
    return 0 if not failed else 1


# ── flatten ───────────────────────────────────────────────────
def _under_archive(rel: Path) -> bool:
    """True if a path (relative to target) lives inside the ``_dumped`` archive."""
    return bool(rel.parts) and rel.parts[0].startswith(ARCHIVE_DIRNAME)


def _nested_files(target: Path) -> list[Path]:
    """Every file under ``target`` that sits in a subfolder, excluding the archive."""
    files = []
    for p in sorted(target.rglob("*")):
        rel = p.relative_to(target)
        if _under_archive(rel):
            continue
        if p.is_file() and rel.parent != Path("."):
            files.append(p)
    return files


def _prune_empty_dirs(target: Path) -> int:
    """Remove now-empty subdirectories (deepest first). Skips the archive. Returns count."""
    removed = 0
    dirs = sorted(
        (p for p in target.rglob("*") if p.is_dir()),
        key=lambda p: len(p.relative_to(target).parts),
        reverse=True,
    )
    for d in dirs:
        if _under_archive(d.relative_to(target)):
            continue
        try:
            if not any(d.iterdir()):
                d.rmdir()
                removed += 1
        except OSError:
            pass
    return removed


def flatten_directory(target: Path, *, dry_run: bool = False) -> int:
    """Collapse every nested file in ``target`` up to the top level.

    Files already at the top stay put. Anything inside the ``_dumped`` archive is
    left untouched. Name collisions are auto-numbered so nothing is lost. After the
    moves, emptied subdirectories are removed. Returns a process exit code.
    """
    files = _nested_files(target)  # snapshot before we mutate the tree
    if not files:
        console.print(f"\n  [warn]nothing to flatten[/warn] — no nested files under [muted]{target}[/muted]\n")
        return 0

    console.print(f"\n  flattening [b]{len(files)}[/b] file{'s' if len(files) != 1 else ''}\n")

    alloc = NameAllocator(listdir_names(target))

    if dry_run:
        renamed = 0
        for f in files:
            chosen, was_renamed = alloc.take(f.name)
            renamed += was_renamed
            note = f" [muted]→ {chosen}[/muted]" if was_renamed else ""
            console.print(f"  [accent]·[/accent] {f.relative_to(target)}{note}")
        console.print("\n  [muted]dry run — nothing moved.[/muted]\n")
        return 0

    moved = renamed = failed = 0
    with console.status("[b]flattening…[/b]", spinner="dots"):
        for f in files:
            chosen, was_renamed = alloc.take(f.name)
            dest = target / chosen
            try:
                shutil.move(str(f), str(dest))
                moved += 1
                renamed += was_renamed
                note = f" [muted]→ {chosen}[/muted]" if was_renamed else ""
                console.print(f"  [ok]✓[/ok] {f.relative_to(target)}{note}")
            except OSError as e:
                failed += 1
                console.print(f"  [bad]✗[/bad] {f.relative_to(target)} [muted]{e}[/muted]")

    removed = _prune_empty_dirs(target)

    rows = [("flattened", f"[ok]{moved}[/ok]" + (f"  [bad]{failed} failed[/bad]" if failed else ""))]
    if renamed:
        rows.append(("auto-numbered", f"{renamed} file{'s' if renamed != 1 else ''}"))
    if removed:
        rows.append(("folders removed", str(removed)))
    rows.append(("target", str(target)))
    summary("flattened" if not failed else "flattened with errors", not failed, rows)
    return 0 if not failed else 1


# ── menu ──────────────────────────────────────────────────────
def _ask_path() -> Path | None:
    """Prompt for a directory. Blank input returns None (back to the menu)."""
    while True:
        raw = Prompt.ask("  [accent]path[/accent]", default="", show_default=False).strip().strip('"').strip("'")
        if not raw:
            return None
        target = Path(raw).expanduser().resolve()
        if not target.exists():
            console.print(f"  [bad]✗[/bad] no such path: [muted]{target}[/muted]")
            continue
        if not target.is_dir():
            console.print(f"  [bad]✗[/bad] not a directory: [muted]{target}[/muted]")
            continue
        return target


def _print_menu() -> None:
    console.print("  [b]what now?[/b]\n")
    console.print("   [accent]1[/accent]  flat dumpie     [muted]unpack everything into the folder, no subfolders[/muted]")
    console.print("   [accent]2[/accent]  modular dumpie  [muted]a folder per zip — keeps structure[/muted]")
    console.print("   [accent]3[/accent]  options")
    console.print("   [accent]q[/accent]  quit")
    console.print()


def _options() -> None:
    while True:
        console.print("  [b]options[/b]\n")
        console.print("   [accent]1[/accent]  flatten an existing directory  [muted]collapse an already-unpacked folder to files only[/muted]")
        console.print("   [accent]2[/accent]  about")
        console.print("   [accent]b[/accent]  back")
        console.print()
        choice = Prompt.ask("  [accent]›[/accent]", choices=["1", "2", "b"], show_choices=False, default="b")
        console.print()
        if choice == "1":
            target = _ask_path()
            if target is not None:
                flatten_directory(target)
        elif choice == "2":
            console.print(f"  [brand]dumpie[/brand] [muted]v{__version__}[/muted]")
            console.print("  [muted]unpacks every zip under a folder, then sweeps the originals into _dumped/.[/muted]")
            console.print("  [muted]flat = all files loose · modular = a folder per zip.[/muted]\n")
        else:
            return


def landing() -> int:
    """Run dumpie's interactive menu. Returns a process exit code."""
    greet()
    while True:
        _print_menu()
        choice = Prompt.ask("  [accent]›[/accent]", choices=["1", "2", "3", "q"], show_choices=False, default="1")
        console.print()
        if choice == "1":
            target = _ask_path()
            if target is not None:
                run(target, Mode.FLAT)
        elif choice == "2":
            target = _ask_path()
            if target is not None:
                run(target, Mode.MODULAR)
        elif choice == "3":
            _options()
        else:
            console.print("  [muted]later.[/muted]\n")
            return 0


# ── cli ───────────────────────────────────────────────────────
def _resolve_dir(raw: str) -> Path | None:
    """Resolve and validate a directory argument, reporting why if it is rejected."""
    target = Path(raw).expanduser().resolve()
    if not target.exists():
        console.print(f"  [bad]✗[/bad] no such path: [muted]{target}[/muted]")
        return None
    if not target.is_dir():
        console.print(f"  [bad]✗[/bad] not a directory: [muted]{target}[/muted]")
        return None
    return target


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="dumpie",
        description="Unpack every zip under a folder. Run with no arguments for the menu.",
    )
    parser.add_argument("--version", action="version", version=f"dumpie {__version__}")
    parser.add_argument("--dry-run", action="store_true", help="show what would happen, write nothing")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--flat", metavar="PATH", help="unpack all files into the folder, no subfolders")
    group.add_argument("--modular", metavar="PATH", help="a folder per zip (keeps structure)")
    group.add_argument("--flatten", metavar="PATH", help="flatten an already-unpacked folder to files only")
    return parser


def main(argv: list[str] | None = None) -> int:
    """dumpie entry point. With no mode flag, opens the interactive menu."""
    args = _build_parser().parse_args(argv)

    if args.flat is not None:
        target = _resolve_dir(args.flat)
        return run(target, Mode.FLAT, dry_run=args.dry_run) if target else 2
    if args.modular is not None:
        target = _resolve_dir(args.modular)
        return run(target, Mode.MODULAR, dry_run=args.dry_run) if target else 2
    if args.flatten is not None:
        target = _resolve_dir(args.flatten)
        return flatten_directory(target, dry_run=args.dry_run) if target else 2

    return landing()


if __name__ == "__main__":
    import sys
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        console.print("\n[muted]aborted[/muted]")
        sys.exit(130)
DUMPIE_EOF

